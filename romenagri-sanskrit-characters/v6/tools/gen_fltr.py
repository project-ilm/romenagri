"""v6 mapping-layer generator. Writes, per script: maps/<xx>.csv, Romenagri/fltr_<xx>_hi, Romenagri/fltr_hi_<xx> (sed scripts, the style of fltr_hi_te).
Pairs come from iscii_map.csv (the repository's own pivot choice) and, for every script, from equal Unicode names (SCRIPT LETTER KA = DEVANAGARI LETTER KA).
usage: gen_fltr.py <Romenagri dir with iscii_map.csv> <out dir>"""
import csv, os, stat, sys, unicodedata
SCRIPTS = {  # code: (Unicode name prefix, tier)
 "bn": ("BENGALI", "A"), "as": ("BENGALI", "A"), "pa": ("GURMUKHI", "A"), "gu": ("GUJARATI", "A"), "or": ("ORIYA", "A"), "ta": ("TAMIL", "A"),
 "te": ("TELUGU", "A"), "kn": ("KANNADA", "A"), "ml": ("MALAYALAM", "A"),
 "si": ("SINHALA", "B"), "brah": ("BRAHMI", "B"), "kthi": ("KAITHI", "B"), "gran": ("GRANTHA", "B"), "shrd": ("SHARADA", "B"),
 "modi": ("MODI", "B"), "tirh": ("TIRHUTA", "B"), "sidd": ("SIDDHAM", "B"), "newa": ("NEWA", "B")}
CSVCOL = {"bn": "Bengali", "as": "Assamese", "pa": "Gurmukhi", "gu": "Gujarati", "or": "Oriya", "ta": "Tamil", "te": "Telugu", "kn": "Kannada", "ml": "Malayalam"}

# Pivot choices for letters with no Devanagari counterpart (decided 12 Nov 2026). Targets already in the v5 core are preferred; Unicode
# Devanagari-block spare letters otherwise. Nothing is added to the v5 core: a spare target that the core has no byte for is a "core limit" in T2.
EXTRA = {"as": {0x09F0: 0x0931, 0x09F1: 0x0979}, "ta": {0x0BB4: 0x0934, 0x0BB1: 0x0931, 0x0BA9: 0x0929}, "ml": {0x0D34: 0x0934, 0x0D31: 0x0931, 0x0D29: 0x0929},
         "bn": {0x09F0: 0x0931, 0x09F1: 0x0979}}
CHILLU = {"ml": {0x0D7A: "\u0923\u094d", 0x0D7B: "\u0928\u094d", 0x0D7C: "\u0930\u094d", 0x0D7D: "\u0932\u094d", 0x0D7E: "\u0933\u094d"}}  # forward only: lossy

def repertoire(prefix):
    return [c for c in range(0x110000) if unicodedata.name(chr(c), "").startswith(prefix + " ")]

def dev_by_suffix():
    d = {}
    for c in range(0x900, 0x980):
        n = unicodedata.name(chr(c), "")
        if n.startswith("DEVANAGARI "): d.setdefault(n[11:], c)
    return d

def build(root):
    rows = list(csv.reader(open(os.path.join(root, "iscii_map.csv"), encoding="utf-8")))
    hdr = rows[0]; res = {}; dev = dev_by_suffix()
    for code, (prefix, tier) in SCRIPTS.items():
        rep = repertoire(prefix); pairs = {}
        for c in rep:  # by name
            n = unicodedata.name(chr(c))[len(prefix) + 1:]
            if n in dev: pairs[c] = (dev[n], "name")
        if code in CSVCOL:  # the repository's table wins
            i = hdr.index(CSVCOL[code])
            for r in rows[1:]:
                if len(r) > i + 1 and r[3] and r[i] and r[i + 1]:
                    try: s = int(r[i + 1], 16); d = ord(r[3][0])
                    except ValueError: continue
                    if len(r[i]) == 1 and len(r[3]) == 1 and s in rep: pairs[s] = (d, "csv")
        for c, d in EXTRA.get(code, {}).items(): pairs[c] = (d, "pivot")
        res[code] = (prefix, tier, rep, pairs)
    return res

def sedfile(path, pairs):
    body = "; ".join("s/%s/%s/g" % (a, b) for a, b in pairs)
    open(path, "w", encoding="utf-8").write('#!/bin/sh\n# Copyright (C) 1993-2026 Abhishek Choudhary; SPDX-License-Identifier: GPL-2.0-or-later\n# generated by v6/tools/gen_fltr.py\nsed "%s"\n' % body)
    os.chmod(path, 0o755)

def main(root, out):
    res = build(root)
    for code, (prefix, tier, rep, pairs) in res.items():
        os.makedirs(out + "/maps", exist_ok=True); os.makedirs(out + "/Romenagri", exist_ok=True)
        with open("%s/maps/%s.csv" % (out, code), "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f); w.writerow(["script_cp", "script_char", "dev_cp", "dev_char", "source", "script_name"])
            for c in rep:
                d, s = pairs.get(c, (None, ""))
                w.writerow(["%04X" % c, chr(c), "" if d is None else "%04X" % d, "" if d is None else chr(d), s, unicodedata.name(chr(c))])
        fwd = [(chr(c), chr(d)) for c, (d, _) in sorted(pairs.items())]
        back = {}
        for c, (d, _) in sorted(pairs.items()): back.setdefault(d, c)   # collisions: first letter wins
        fwd += [(chr(c), t) for c, t in CHILLU.get(code, {}).items()]
        sedfile("%s/Romenagri/fltr_%s_hi" % (out, code), fwd)
        sedfile("%s/Romenagri/fltr_hi_%s" % (out, code), [(chr(d), chr(c)) for d, c in sorted(back.items())])
    return res

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
