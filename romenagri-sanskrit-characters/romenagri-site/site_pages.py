def cps_str(cps):
    return " ".join("U+%04X" % c for c in cps)


def chars(cps):
    return "".join(chr(c) for c in cps)


def hexb(b):
    return " ".join("%02X" % x for x in b)


def units(cps):
    u = []
    for c in cps:
        if c > 0xFFFF:
            c -= 0x10000
            u += [0xD800 + (c >> 10), 0xDC00 + (c & 0x3FF)]
        else:
            u.append(c)
    return u


