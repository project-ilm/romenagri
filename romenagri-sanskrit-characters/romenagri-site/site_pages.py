def run_notebook(bin_dir, nb_dir):
    """Runs the cells in one namespace with ROMENAGRI_BIN set; returns the nbformat 4 document (as a dict) with the outputs of the run."""
    ns = {"__name__": "__main__"}
    cells, count = [], 0
    old_cwd = os.getcwd()
    old_bin = os.environ.get("ROMENAGRI_BIN")
    os.environ["ROMENAGRI_BIN"] = bin_dir
    os.chdir(nb_dir)
    try:
        for i, (kind, src) in enumerate(NB_CELLS):
            cell = {"cell_type": kind, "id": "cell%02d" % i, "metadata": {}, "source": src.splitlines(True)}
            if kind == "code":
                count += 1
                buf = io.StringIO()
                with contextlib.redirect_stdout(buf):
                    exec(compile(src, "<cell %d>" % i, "exec"), ns)
                text = buf.getvalue()
                cell["execution_count"] = count
                cell["outputs"] = [{"output_type": "stream", "name": "stdout", "text": text.splitlines(True)}] if text else []
            cells.append(cell)
    finally:
        os.chdir(old_cwd)
        if old_bin is None:
            os.environ.pop("ROMENAGRI_BIN", None)
        else:
            os.environ["ROMENAGRI_BIN"] = old_bin
    return {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                         "language_info": {"name": "python", "version": "3"}}, "nbformat": 4, "nbformat_minor": 5}


