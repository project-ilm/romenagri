def record_case(c, cps, via):
    """For each form: the ACII bytes, the Romenagri (or a crash) and the code points that come out.  All written by the C programs."""
    rows = {}
    for f in FORMS:
        a, _ = c.u2a(units(cps), f)
        rmn, out = None, None
        if via:
            k, v = c.a2r(a)
            if k == "text":
                rmn = v.decode("latin-1")
                k2, b = c.r2a(v)
                out = c.a2u(b, f) if k2 == "bytes" else None
            else:
                rmn = "crash"
                out = c.a2u(a, f)
        else:
            out = c.a2u(a, f)
        rows[f] = (hexb(a), rmn, out)
    return rows


def group_forms(rows):
    """[(forms, (acii, rmn, out))], the forms that give the same line together, in the order of FORMS"""
    groups = []
    for f in FORMS:
        for g in groups:
            if g[1] == rows[f]:
                g[0].append(f)
                break
        else:
            groups.append(([f], rows[f]))
    return groups


def uni_cell(units_):
    cps = [ord(ch) for ch in "".join(chr(u) for u in units_)]
    return "%s <code>%s</code>" % (esc(chars(cps)), esc(cps_str(cps)))


def cps_cell(cps):
    return "%s <code>%s</code>" % (esc(chars(cps)), esc(cps_str(cps)))


def rmn_cell(r):
    if r is None:
        return "(not run)"
    if r == "crash":
        return '<span class="crash">acii2rmn crashes (exit status 139)</span>'
    return "<code>%s</code>" % esc(r)


