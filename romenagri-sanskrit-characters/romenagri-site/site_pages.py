def fragment_cases(c):
    out = []
    order = []
    for cid, label, cps, via in CASES:
        if cid not in order:
            order.append(cid)
    for cid in order:
        title, what, decision = CASE_TEXT[cid]
        out.append('<div class="case" id="%s">\n<h3>%s. %s</h3>\n<p>%s</p>\n<p class="decision"><strong>Decision.</strong> %s</p>' % (cid.lower(), cid, title, what, decision))
        out.append('<div class="scroll"><table>\n<tr><th>Case</th><th>In</th><th>Form</th><th>ACII</th><th>Romenagri</th><th>Out</th></tr>')
        for cid2, label, cps, via in CASES:
            if cid2 != cid:
                continue
            rows = record_case(c, cps, via)
            groups = group_forms(rows)
            for i, (forms, (a, rmn, outu)) in enumerate(groups):
                label_cell = esc(label) if i == 0 else ""
                in_cell = cps_cell(cps) if i == 0 else ""
                out_cps = [ord(ch) for ch in "".join(chr(u) for u in outu)]
                out.append("<tr><td>%s</td><td>%s</td><td>%s</td><td class=\"mono\">%s</td><td>%s</td><td>%s</td></tr>" % (
                    label_cell, in_cell, "all three" if len(forms) == 3 else ", ".join(forms), a, rmn_cell(rmn), cps_cell(out_cps)))
        out.append("</table></div>")
        if cid == "C5":
            a, err = c.u2a(units([0x0928, 0xE9]), "asis", True)
            out.append('<p>With <code>uni2acii -w</code> the same input writes this on stderr (the bytes are the same):</p>\n<pre class="wrap"><code>%s</code></pre>' % esc("\n".join(err)))
