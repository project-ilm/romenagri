DEV_RUN = re.compile("[ऀ-ॿ‌‍◌]*[ऀ-ॿ][ऀ-ॿ‌‍◌]*")
SKIP_TAGS = ("script", "style", "textarea", "title")


def devwrap(page):
    """Wraps every run of Devanagari in the text of the page in <span class="dev" lang="hi">, so that a font for it is chosen."""
    out, skip = [], None
    for part in re.split(r"(<[^>]+>)", page):
        if part.startswith("<") and part.endswith(">"):
            m = re.match(r"</?\s*([a-zA-Z0-9]+)", part)
            if m:
                tag = m.group(1).lower()
                if tag in SKIP_TAGS:
                    skip = None if part.startswith("</") else tag
            out.append(part)
        elif skip:
            out.append(part)
        else:
            out.append(DEV_RUN.sub(lambda m: '<span class="dev" lang="hi">%s</span>' % m.group(0), part))
    return "".join(out)


def expand(text, pieces):
    """{{name}} is a generated piece (which may itself hold {{u:...}}); {{u:0958,0959}} is the characters with these code points"""
    for k, v in pieces.items():
        text = text.replace("{{%s}}" % k, v)
    text = re.sub(r"\{\{u:([0-9A-Fa-f, ]+)\}\}", lambda m: esc(chars([int(x, 16) for x in m.group(1).replace(" ", "").split(",")])), text)
    left = re.findall(r"\{\{[^}]*\}\}", text)
    assert not left, left
    return text


