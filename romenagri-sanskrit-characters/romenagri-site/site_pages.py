def stack_trace(data, rows):
    """the stack of acii2rmn after each byte (the same machine as tests/model.py model_encode), for the worked example"""
    stack, steps = [], []
    for b in data:
        hit = None
        for key, bs in rows:
            if bs and bs[0] == b:
                hit = key
                break
        if hit is not None and hit[:1] == "^" and stack:
            stack.pop()
            if hit[1:2] == "z":
                t1 = stack.pop()
                if t1 == "h":
                    t2 = stack.pop()
                    stack.extend("_rdha" if t2 == "d" else t2 + "hza")
                elif t1 == "d":
                    stack.extend("_rda")
                else:
                    stack.extend(t1 + "za")
            else:
                stack.extend(hit[1:])
        elif hit is not None:
            stack.extend(hit)
        else:
            stack.append(chr(b))
        steps.append((b, hit, "".join(stack)))
    return steps


