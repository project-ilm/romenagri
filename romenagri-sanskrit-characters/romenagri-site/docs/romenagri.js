  /* the stack machine of acii2rmn(): tok is an array of bytes without a zero.  Returns a Latin-1 string; throws {crash: "..."} where the
     C code takes the character of an empty stack. */
  function acii2rmnTok(tok) {
    var stack = [];
    var ef = ACII[0][1][0];                         /* the ISCII attribute prefix, EF */
    function pop1() {
      if (stack.length === 0) throw { crash: "acii2rmn: a nukta takes two characters off the stack and it holds fewer (for example a nukta after a halant, E8 E9)" };
      return stack.pop();
    }
    function pushAll(s) { for (var k = 0; k < s.length; k++) stack.push(s.charAt(k)); }
    for (var i = 0; i < tok.length; i++) {
      var b = tok[i], hit = -1;
      for (var j = 0; j < ACII.length; j++) {
        if (ACII[j][1].length > 0 && ACII[j][1][0] === b) { hit = j; break; }   /* the first row whose first byte is b */
      }
      if (hit >= 0) {
        var key = ACII[hit][0];
        if (key.charAt(0) === "^" && stack.length > 0) {      /* a dependent sign, or the halant: the 'a' of the consonant goes */
          stack.pop();
          if (key.charAt(1) === "z") {                        /* the nukta: ka + nukta is kza, with two exceptions */
            var t1 = pop1();
            if (t1 === "h") {
              var t2 = pop1();
              if (t2 === "d") pushAll("_rdha");
              else { stack.push(t2); pushAll("hza"); }
            } else if (t1 === "d") pushAll("_rda");
            else { stack.push(t1); pushAll("za"); }
          } else pushAll(key.slice(1));
        } else pushAll(key);
      } else {
        var prev = i > 0 ? tok[i - 1] : null;
        if (prev !== ef) stack.push(String.fromCharCode(b));
      }
    }
    return stack.join("");
  }

  function isLetter(c) { return (c >= 65 && c <= 90) || (c >= 97 && c <= 122) || c === 95; }   /* [A-Za-z_] */

  /* the filter acii2rmn: letters of English in the ACII text are wrapped as "e_..."; every run of the other bytes but newline, backspace,
     a caret and a double quote goes through the decoder; those four are copied.  Returns {text} or {crash}. */
  function acii2rmn(bytes) {
    if (typeof bytes === "string") bytes = toUnits(bytes);
    var out = "", i = 0, n = bytes.length;
    try {
      while (i < n) {
        var c = bytes[i];
        if (isLetter(c)) {
          var j = i;
          while (j < n && isLetter(bytes[j])) j++;
          out += '"e_' + String.fromCharCode.apply(null, bytes.slice(i, j)) + '"';
          i = j;
        } else if (c === 10 || c === 8 || c === 34 || c === 94) {
          out += String.fromCharCode(c);
          i++;
        } else {
          var k = i;
          while (k < n && !isLetter(bytes[k]) && bytes[k] !== 10 && bytes[k] !== 8 && bytes[k] !== 34 && bytes[k] !== 94) k++;
          var tok = bytes.slice(i, k), z = tok.indexOf(0);
          if (z >= 0) tok = tok.slice(0, z);                  /* the decoder gets a C string */
          out += acii2rmnTok(tok);
          i = k;
        }
      }
    } catch (e) {
      if (e && e.crash) return { crash: e.crash };
      throw e;
    }
    return { text: out };
  }

  /* ---- rmn2acii.c and rmn2acii.lex ------------------------------------------------------------------------------------------- */
  var LEV1 = "|kgcjtdnpbmyrlwsxh_^";

  /* the parser, on a run of [A-Za-z_]: one function for each state of rmn2acii.c, with the twelve guards of patch 0002 and the branches of
     patch 0001.  Returns an array of bytes; throws {crash: "..."} where lookup() would return NULL. */
  function rmn2aciiRun(s) {
    var out = [], n = s.length;

    function at(i) { return i < n ? s.charAt(i) : "\0"; }
    function lk(key) {
      if (!(key in keyTable)) throw { crash: "rmn2acii: the table has no row for the key '" + key + "'" };
      var v = keyTable[key];
      for (var k = 0; k < v.length; k++) out.push(v[k]);
    }
    function raw(c) { if (c !== "\0") out.push(c.charCodeAt(0)); }
    function halant() { lk("^"); }
    function startsToken(c) { return c === "\0" || LEV1.indexOf(c) >= 0; }
    function noPartner(c) { return c === "_" || c === "\0"; }
    function lastIsHalant() { return out.length > 0 && out[out.length - 1] === keyTable["^"][0]; }
    function vocalic(indep, dep) {
      if (lastIsHalant()) { out.pop(); lk(dep); } else lk(indep);
    }

    function level1(i) {
      if (i >= n) return;
      var c = s.charAt(i);
      if (c === "|") { lk("|"); level1(i + 1); }
      else if ("nmywxr".indexOf(c) >= 0) { lk(c + "a"); level2a(i + 1); }
      else if ("gtdpbslkj".indexOf(c) >= 0) level2b(i + 1, c);
      else if (c === "c") {
        if (noPartner(at(i + 1))) { raw(c); level1(i + 1); }          /* guard: a 'c' with no 'h' after it is the letter c */
        else level2b(i + 2, "ch");
      }
      else if (c === "_") level2c(i + 1);
      else if (c === "^") matra(i + 1);
      else { raw(c); level1(i + 1); }
    }

    function level2b(i, stem) {
      if (i >= n) { lk(stem + "a"); halant(); return; }
      var c = s.charAt(i);
      if (c === "h") { lk(stem + "ha"); level2a(i + 1); }
      else if (c === "v" && !noPartner(at(i + 1))) { lk(stem + "vra"); level2a(i + 2); }   /* guard: no 'r' after the v */
      else { lk(stem + "a"); level2a(i); }
    }

    function level2a(i) {
      if (i >= n) { halant(); return; }
      if (LEV1.indexOf(s.charAt(i)) >= 0) { halant(); level1(i); }
      else matra(i);
    }

    function matra(i) {
      if (i >= n) { halant(); return; }
      var c = s.charAt(i), d;
      if (c === "i") { lk("^i"); level1(i + 1); }
      else if (c === "u") { lk("^u"); level1(i + 1); }
      else if (c === "e") {
        if (noPartner(at(i + 1))) { raw(c); level1(i + 1); }
        else { lk("^ee"); level1(i + 2); }
      }
      else if (c === "z") { lk("^za"); level2a(i + 1); }
      else if (c === "_") {
        if (at(i + 1) === "l" && at(i + 2) === "i") { lk("^_li"); level1(i + 3); }
        else if (at(i + 1) === "l" && at(i + 2) === "e" && at(i + 3) === "e") { lk("^_lee"); level1(i + 4); }
        else if (at(i + 1) === "r" && at(i + 2) === "e" && at(i + 3) === "e") { lk("^_ree"); level1(i + 4); }
        else if (noPartner(at(i + 1)) || noPartner(at(i + 2))) level1(i);       /* guard: the underscore is read again */
        else { lk("^_ri"); level1(i + 3); }
      }
      else if (c === "o") {
        d = at(i + 1);
        if (noPartner(d)) { raw(c); level1(i + 1); }
        else if (d === "o") { lk("^oo"); level1(i + 2); }
        else if (d === "w") { lk("^ow"); level1(i + 2); }
        else if (d === "a") { lk("^oa"); level1(i + 2); }
        else if (d === "u") { lk("^ou"); level1(i + 2); }
        else { raw(d); level1(i + 2); }
      }
      else if (c === "a") {
        d = at(i + 1);
        if (startsToken(d)) level1(i + 1);
        else if (d === "a") { lk("^aa"); level1(i + 2); }
        else if (d === "e") {
          if (at(i + 2) === "e") { lk("^aee"); level1(i + 3); }
          else { lk("^ae"); level1(i + 2); }
        }
        else if (d === "i") { lk("^ai"); level1(i + 2); }
        else if (d === "o") { lk("^ao"); level1(i + 2); }
        else if (d === "u") { lk("^au"); level1(i + 2); }
        else { raw(d); level1(i + 2); }
      }
      else { raw(c); level1(i + 1); }
    }

    function level2c(i) {
      if (i >= n) { halant(); return; }
      var c = s.charAt(i), d;
      if (c === "s") { lk("_s"); level1(i + 1); }
      else if (c === "u") { lk("_u"); level1(i + 1); }
      else if (c === "m") { lk("_m"); level1(i + 1); }
      else if (c === "i") { lk("_i"); level1(i + 1); }
      else if (c === "e") {
        if (noPartner(at(i + 1))) { raw(c); level1(i + 1); }
        else { lk("_ee"); level1(i + 2); }
      }
      else if (c === "y") {
        if (noPartner(at(i + 1))) { raw(c); level1(i + 1); }
        else { lk("_yna"); level2a(i + 2); }
      }
      else if (c === "t") level2b(i + 1, "_t");
      else if (c === "d") level2b(i + 1, "_d");
      else if (c === "h") {
        if (at(i + 1) === "h") { lk("_hh"); level1(i + 2); }
        else { lk("_ha"); level2a(i + 1); }
      }
      else if (c === "o") {
        d = at(i + 1);
        if (noPartner(d)) { raw(c); level1(i + 1); }
        else if (d === "o") { lk("_oo"); level1(i + 2); }
        else if (d === "w") { lk("_ow"); level1(i + 2); }
        else if (d === "a") { lk("_oa"); level1(i + 2); }
        else if (d === "u") { lk("_ou"); level1(i + 2); }
        else if (d === "m") { lk("_om"); level1(i + 2); }
        else { raw(d); level1(i + 2); }
      }
      else if (c === "n") {
        d = at(i + 1);
        if (noPartner(d)) { raw(c); level1(i + 1); }
        else if (d === "a") { lk("_na"); level1(i + 2); }
        else if (d === "n") { lk("_nna"); level2a(i + 2); }
        else if (d === "g") { lk("_nga"); level2a(i + 2); }
        else if (d === "z") { lk("_nza"); level2a(i + 2); }
        else { raw(d); level1(i + 2); }
      }
      else if (c === "r") {
        d = at(i + 1);
        if (noPartner(d)) { raw(c); level1(i + 1); }
        else if (d === "i") {
          if (lastIsHalant()) { out.pop(); lk("^_ri"); } else lk("_ri");
          level1(i + 2);
        }
        else if (d === "d") level2b(i + 2, "_rd");
        else if (d === "r") level2b(i + 2, "_rr");
        else if (d === "e" && at(i + 2) === "e") { vocalic("_ree", "^_ree"); level1(i + 3); }
        else { raw(d); level1(i + 2); }
      }
      else if (c === "a") {
        d = at(i + 1);
        if (startsToken(d)) { lk("_a"); level1(i + 1); }
        else if (d === "a") { lk("_aa"); level1(i + 2); }
        else if (d === "e") {
          if (at(i + 2) === "e") { lk("_aee"); level1(i + 3); }
          else { lk("_ae"); level1(i + 2); }
        }
        else if (d === "i") { lk("_ai"); level1(i + 2); }
        else if (d === "o") { lk("_ao"); level1(i + 2); }
        else if (d === "u") { lk("_au"); level1(i + 2); }
        else { raw(d); level1(i + 2); }
      }
      else if (c === "j") {
        d = at(i + 1);
        if (noPartner(d)) { raw(c); level1(i + 1); }
        else if (d === "z") { lk("_jza"); level2a(i + 2); }
        else { raw(d); level1(i + 2); }
      }
      else if (c === "l") {
        if (at(i + 1) === "i") { vocalic("_li", "^_li"); level1(i + 2); }
        else if (at(i + 1) === "e" && at(i + 2) === "e") { vocalic("_lee", "^_lee"); level1(i + 3); }
        else { raw(c); level1(i + 1); }
      }
      else if (c === "v") {
        d = at(i + 1);
        if (d === "d") { lk("_vd"); level1(i + 2); }
        else if (d === "u" || d === "n" || d === "g" || d === "c") { lk("_v" + d + "a"); level2a(i + 2); }   /* accents are written like the nukta */
        else { raw("v"); level1(i + 1); }
      }
      else { raw(c); level1(i + 1); }
    }

    level1(0);
    return out;
  }

  /* the filter rmn2acii: "e_..." is unwrapped, every run of [A-Za-z_] goes through the parser, the rest is copied.
     text: a string.  Returns {bytes} or {crash}. */
  function rmn2acii(text) {
    var out = [], i = 0, n = text.length;
    try {
      while (i < n) {
        var c = text.charCodeAt(i);
        if (c === 34 && text.substr(i, 3) === '"e_') {
          var q = text.indexOf('"', i + 3);
          if (q >= 0) {
            for (var k = i + 3; k < q; k++) out.push(text.charCodeAt(k) & 255);
            i = q + 1;
            continue;
          }
        }
        if (isLetter(c)) {
          var j = i;
          while (j < n && isLetter(text.charCodeAt(j))) j++;
          var r = rmn2aciiRun(text.slice(i, j));
          for (var m = 0; m < r.length; m++) out.push(r[m]);
          i = j;
        } else {
          out.push(c & 255);
          i++;
        }
      }
    } catch (e) {
      if (e && e.crash) return { crash: e.crash };
      throw e;
    }
    return { bytes: out };
  }

